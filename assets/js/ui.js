// Utilitários de interface: templates seguros, ícones, toasts, CSV e cópia.

class Raw {
  constructor(s) {
    this.s = s;
  }
  toString() {
    return this.s;
  }
}

export const raw = (s) => new Raw(s);

const ESC = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };
export const esc = (v) => String(v ?? '').replace(/[&<>"']/g, (c) => ESC[c]);

function piece(v) {
  if (v === null || v === undefined || v === false) return '';
  if (v instanceof Raw) return v.s;
  if (Array.isArray(v)) return v.map(piece).join('');
  return esc(v);
}

/** Template literal que escapa interpolações (exceto raw()/html``). */
export function html(strings, ...vals) {
  let out = strings[0];
  vals.forEach((v, i) => {
    out += piece(v) + strings[i + 1];
  });
  return new Raw(out);
}

/** Realça os termos da busca dentro de um texto. */
export function mark(text, query) {
  const t = String(text ?? '');
  const tokens = String(query ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .split(/\s+/)
    .filter((x) => x.length > 1);
  if (!tokens.length) return esc(t);
  const base = t.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
  // O texto normalizado pode ter tamanho diferente do original apenas quando
  // há caracteres combinantes já decompostos; nesse caso não realçamos.
  if (base.length !== t.length) return esc(t);
  const marks = new Array(t.length).fill(false);
  for (const tok of tokens) {
    let i = base.indexOf(tok);
    while (i !== -1) {
      for (let k = i; k < i + tok.length; k++) marks[k] = true;
      i = base.indexOf(tok, i + tok.length);
    }
  }
  let out = '';
  let open = false;
  for (let i = 0; i < t.length; i++) {
    if (marks[i] && !open) (out += '<mark>'), (open = true);
    if (!marks[i] && open) (out += '</mark>'), (open = false);
    out += esc(t[i]);
  }
  return open ? out + '</mark>' : out;
}

